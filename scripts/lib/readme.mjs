// Builds README.md from the same content the SVGs are drawn from, so the alt
// text always matches what the images say.

import { esc } from './svg.mjs';

function picture(name, alt) {
  return `<picture><source media="(prefers-color-scheme: dark)" srcset="assets/${name}-dark.svg"><img alt="${esc(alt)}" src="assets/${name}-light.svg"></picture>`;
}

export function renderReadme({ accounts, header, links, toolbox, work, now, changelog, footer }) {
  const buttons = links.map((l) => `<a href="${esc(l.href)}">${picture(`btn-${l.id}`, l.label)}</a>`).join('\n');

  const workBlocks = work.map((item) => {
    const alt = [`${item.title}, ${item.date}.`, item.subtitle, ...item.bullets, `Stack: ${item.chips.join(', ')}.`].join(' ');
    const img = picture(`work-${item.id}`, alt);
    return item.href ? `<a href="${esc(item.href)}">${img}</a>` : img;
  });

  const views = `https://komarev.com/ghpvc/?username=${accounts.github}&label=profile%20views&color=6d4aff&style=flat-square`;

  return [
    '<!-- Generated by scripts/build.mjs from profile/content.mjs. Edit those files, not this one. -->',
    '',
    picture('header', `${header.name}, ${header.title}. ${header.location}. ${header.bio}`),
    '',
    `<p>\n${buttons}\n</p>`,
    '',
    picture('toolbox', `Toolbox. ${toolbox.map(([k, v]) => `${k}: ${v}`).join('. ')}.`),
    '',
    '### Selected work',
    '',
    ...workBlocks.flatMap((block) => [block, '']),
    '### Now',
    '',
    now,
    '',
    picture('activity', `Combined GitLab (${accounts.gitlab}) and GitHub (${accounts.github}) contribution graph for the last 12 months, refreshed daily, with recently shipped work.`),
    '',
    '### Changelog',
    '',
    picture('changelog', `Changelog. ${changelog.map((r) => `${r.version}: ${r.title}. ${r.desc}`).join(' ')}`),
    '',
    '---',
    '',
    `<sub>${esc(footer)}</sub>&nbsp;&nbsp;<img alt="Profile views" src="${views}">`,
    '',
  ].join('\n');
}
